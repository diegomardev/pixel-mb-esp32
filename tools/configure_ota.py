"""Generate private OTA credentials and configure PlatformIO's espota uploader."""
from pathlib import Path
from SCons.Script import COMMAND_LINE_TARGETS
import hashlib
import json
import os
import secrets
Import('env')
root = Path(env.subst('$PROJECT_DIR'))
config_path = root / 'ota.local.json'
if not config_path.exists():
    config_path.write_text(json.dumps({'host': 'pixel-mb.local', 'password': secrets.token_urlsafe(24)}, indent=2) + '\n')
    os.chmod(config_path, 0o600)
config = json.loads(config_path.read_text())
password = config.get('password', '')
if not isinstance(password, str) or len(password) < 16:
    raise ValueError('ota.local.json: password must contain at least 16 characters')
host = config.get('host', 'pixel-mb.local')
if not isinstance(host, str) or not host.strip():
    raise ValueError('ota.local.json: host must be a hostname or IP address')
header = root / 'include/LocalOtaConfig.h'
content = '#pragma once\n// Generated by tools/configure_ota.py; do not commit.\n#define OTA_PASSWORD_HASH "' + hashlib.md5(password.encode()).hexdigest() + '"\n'
content += '#define OTA_HTTP_DIGEST "' + hashlib.md5(('admin:Pixel-MB OTA:' + password).encode()).hexdigest() + '"\n'
content += "#define OTA_HTTP_PASSWORD " + json.dumps(password) + "\n"
if not header.exists() or header.read_text() != content:
    header.write_text(content)
if env.GetProjectOption('upload_protocol', '') in ('espota', 'custom'):
    if any(target in COMMAND_LINE_TARGETS for target in ('uploadfs', 'uploadfsota')):
        raise ValueError('OTA uploadfs disabled: it would replace saved animations and configuration. Use firmware upload.')
    # Explicit CLI --upload-port overrides the local default when needed.
    if env.GetProjectOption('upload_protocol', '') == 'espota' and not env.subst('$UPLOAD_PORT'):
        env.Replace(UPLOAD_PORT=host)

